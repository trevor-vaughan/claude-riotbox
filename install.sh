#!/usr/bin/env bash
# install.sh — Install RiotBox for the current user (rootless, XDG layout).
# Lays the app tree into $XDG_DATA_HOME/riotbox and symlinks the entrypoint
# into a directory on your PATH. Re-runnable; never overwrites user config
# and never touches session dirs or git backups that share the data tree.
#
# Usage:
#   ./install.sh --build             # compile riotbox-core here (needs Go)
#   ./install.sh --binary            # download the signed release binary (needs curl, cosign)
#   ./install.sh --build ~/bin       # custom bin dir (default ~/.local/bin)
#
# Exactly one of --build or --binary is required: the installer never picks
# between compiling locally and fetching from the network on your behalf.
set -euo pipefail

SRC_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# riotbox-core is stamped with VERSION and the launcher refuses a binary
# whose version differs, so an unversioned tree cannot be installed. Same
# pattern as scripts/build-core.sh; keep the two in step.
if ! VERSION="$(cat "${SRC_DIR}/VERSION" 2>/dev/null)" ||
	[[ ! "${VERSION}" =~ ^[0-9]+\.[0-9]+\.[0-9]+([-+][0-9A-Za-z.-]+)?$ ]]; then
	echo "ERROR: ${SRC_DIR}/VERSION is missing or not a semantic version (got '${VERSION:-}'); nothing installed." >&2
	exit 1
fi

DATA_DIR="${XDG_DATA_HOME:-${HOME}/.local/share}/riotbox"
CONFIG_DIR="${XDG_CONFIG_HOME:-${HOME}/.config}/riotbox"

usage() {
	echo "usage: install.sh --build|--binary [BIN_DIR]" >&2
	echo "       exactly one of --build or --binary is required" >&2
}

CORE_SOURCE=""
BIN_DIR=""
for arg in "$@"; do
	case "${arg}" in
	--build | --binary)
		if [[ -n "${CORE_SOURCE}" ]]; then
			echo "ERROR: give exactly one of --build or --binary." >&2
			usage
			exit 1
		fi
		CORE_SOURCE="${arg#--}"
		;;
	-*)
		echo "ERROR: unknown option: ${arg}" >&2
		usage
		exit 1
		;;
	*)
		if [[ -n "${BIN_DIR}" ]]; then
			echo "ERROR: more than one BIN_DIR given." >&2
			usage
			exit 1
		fi
		BIN_DIR="${arg}"
		;;
	esac
done
if [[ -z "${CORE_SOURCE}" ]]; then
	echo "ERROR: give exactly one of --build or --binary." >&2
	usage
	exit 1
fi
BIN_DIR="${BIN_DIR:-${HOME}/.local/bin}"

# Runtime app tree shipped to the data dir. Dev-only material (Taskfile,
# .taskfiles, tests, docs, .goreleaser.yaml, .github) is intentionally excluded.
# Top-level configs/ is also excluded: it is a host-specific build artifact
# regenerated by scripts/build.sh from the user's tool configs at build time.
#
# Each entry is removed from DATA_DIR before re-copying. Anything in DATA_DIR
# that is NOT in this list (notably session dirs, backups/, and any user
# additions) is preserved across upgrades — wiping DATA_DIR wholesale would
# destroy the safety backups described in README and silently lose work.
APP_PATHS=(bin libexec scripts agents container Containerfile .dockerignore VERSION)
APP_MARKER=".riotbox-app"

echo "Installing RiotBox ${VERSION} → ${DATA_DIR}"

# Refuse to touch a DATA_DIR that exists but does not look like a RiotBox
# install: a user could have pointed XDG_DATA_HOME at something with their
# own data, and we would rather error than wipe it. The marker file is
# created on first install and re-asserted on every upgrade.
if [[ -e "${DATA_DIR}" ]] && [[ ! -f "${DATA_DIR}/${APP_MARKER}" ]]; then
	# An existing tree without a marker that nevertheless contains all of
	# the known app paths is a pre-marker install. Treat it as ours so the
	# first upgrade past this commit succeeds without manual intervention.
	is_legacy_app_tree=true
	for p in "${APP_PATHS[@]}"; do
		[[ -e "${DATA_DIR}/${p}" ]] || {
			is_legacy_app_tree=false
			break
		}
	done
	if [[ "${is_legacy_app_tree}" != true ]]; then
		echo "ERROR: ${DATA_DIR} exists but is not a RiotBox install tree." >&2
		echo "       (no ${APP_MARKER} marker and missing expected app paths)" >&2
		echo "       Remove or move it manually if you really want to install here." >&2
		exit 1
	fi
fi

# ── riotbox-core ─────────────────────────────────────────────────────────
# Obtained into a private temp dir before the app tree is touched, so a
# failed build, download or verification leaves an existing install as it
# was.
CORE_TMP="$(mktemp -d)"
trap 'rm -rf "${CORE_TMP}"' EXIT
CORE_BIN="${CORE_TMP}/riotbox-core"
RELEASE_REPO="trevor-vaughan/claude-riotbox"
# Oldest cosign --binary trusts, per major line. Below 2.4.2 cosign cannot
# read the Sigstore bundle format the release signs with (cosign v3), and
# GHSA-whqx-f9j3-ch6m is fixed only in 2.6.2 and 3.0.4.
COSIGN_FLOOR_V2="2.6.2"
COSIGN_FLOOR_V3="3.0.4"

fetch_release_core() {
	local machine arch
	machine="$(uname -m)"
	case "${machine}" in
	x86_64) arch=amd64 ;;
	aarch64 | arm64) arch=arm64 ;;
	*)
		echo "ERROR: no release binary for ${machine}; use --build instead." >&2
		return 1
		;;
	esac
	local tool
	for tool in curl cosign tar sha256sum; do
		if ! command -v "${tool}" >/dev/null 2>&1; then
			echo "ERROR: --binary needs ${tool}; install it or use --build." >&2
			return 1
		fi
	done

	# `cosign version` prints a `GitVersion:    vX.Y.Z` line, possibly after
	# a banner. Anything that is not a plain release version is refused.
	local cosign_out="" cosign_raw cosign_ver floor
	if ! cosign_out="$(cosign version 2>/dev/null)"; then
		cosign_out=""
	fi
	cosign_raw="$(awk '$1 == "GitVersion:" { print $2; exit }' <<<"${cosign_out}")"
	cosign_ver="${cosign_raw#v}"
	floor=""
	if [[ "${cosign_ver}" =~ ^([0-9]+)\.[0-9]+\.[0-9]+$ ]]; then
		if ((10#${BASH_REMATCH[1]} == 2)); then
			floor="${COSIGN_FLOOR_V2}"
		elif ((10#${BASH_REMATCH[1]} >= 3)); then
			floor="${COSIGN_FLOOR_V3}"
		fi
	fi
	if [[ -z "${floor}" ]] || ! printf '%s\n' "${floor}" "${cosign_ver}" | sort -V -C; then
		echo "ERROR: --binary needs cosign ${COSIGN_FLOOR_V2}+ or ${COSIGN_FLOOR_V3}+ (found ${cosign_raw:-no version}); upgrade cosign or use --build." >&2
		return 1
	fi

	# VERSION only changes in release commits, so a checkout past vX still
	# says X, and vX's binary would pass the launcher's version check while
	# computing keys by vX's rules. Only a checkout that is exactly the tag,
	# or a tree that is not a git checkout (an unpacked source tarball, or
	# no git installed), gets the release binary. git runs without the
	# caller's config or GIT_* redirection; safe.directory admits this tree.
	local reason="" src_phys top head tagged rc
	if command -v git >/dev/null 2>&1; then
		src_phys="$(cd "${SRC_DIR}" && pwd -P)"
		local -a git_src=(env -u GIT_DIR -u GIT_WORK_TREE -u GIT_INDEX_FILE -u GIT_COMMON_DIR
			-u GIT_OBJECT_DIRECTORY -u GIT_CEILING_DIRECTORIES
			GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_SYSTEM=/dev/null GIT_CONFIG_NOSYSTEM=1
			git -c "safe.directory=${src_phys}" -c core.fsmonitor=false -C "${src_phys}")
		# Only this tree's own checkout counts: a tarball unpacked inside
		# some other repository is still a tarball.
		if top="$("${git_src[@]}" rev-parse --show-toplevel 2>/dev/null)" && [[ "${top}" == "${src_phys}" ]]; then
			if ! tagged="$("${git_src[@]}" rev-parse -q --verify "refs/tags/v${VERSION}^{commit}")"; then
				reason="there is no tag v${VERSION}"
			elif ! head="$("${git_src[@]}" rev-parse -q --verify HEAD)" || [[ "${head}" != "${tagged}" ]]; then
				reason="HEAD is not the commit tagged v${VERSION}"
			else
				rc=0
				"${git_src[@]}" diff --quiet --no-ext-diff --no-textconv HEAD -- \
					"${APP_PATHS[@]}" cmd internal go.mod go.sum || rc=$?
				if ((rc == 1)); then
					reason="tracked files are modified"
				elif ((rc != 0)); then
					reason="git diff failed"
				fi
			fi
		fi
	fi
	if [[ -n "${reason}" ]]; then
		echo "ERROR: --binary installs the v${VERSION} release binary, but this checkout is not exactly v${VERSION} (${reason}); use --build." >&2
		return 1
	fi

	local archive="riotbox-core_${VERSION}_linux_${arch}.tar.gz"
	local base="https://github.com/${RELEASE_REPO}/releases/download/v${VERSION}"
	local f
	echo "Fetching riotbox-core v${VERSION} (${arch}) from GitHub releases…"
	for f in "${archive}" checksums.txt checksums.txt.sigstore.json; do
		if ! curl --proto '=https' --tlsv1.2 --fail --silent --show-error --location \
			-o "${CORE_TMP}/${f}" "${base}/${f}"; then
			echo "ERROR: could not download ${base}/${f} — is this checkout a release? Use --build otherwise." >&2
			return 1
		fi
	done

	# Authenticity: checksums.txt was signed by this repository's release
	# workflow at this exact tag (Sigstore keyless, GitHub OIDC).
	if ! cosign verify-blob \
		--bundle "${CORE_TMP}/checksums.txt.sigstore.json" \
		--certificate-identity "https://github.com/${RELEASE_REPO}/.github/workflows/release.yml@refs/tags/v${VERSION}" \
		--certificate-oidc-issuer "https://token.actions.githubusercontent.com" \
		"${CORE_TMP}/checksums.txt"; then
		echo "ERROR: signature verification failed for ${base}/checksums.txt; nothing installed." >&2
		return 1
	fi
	# Integrity: the archive is the one the signed list names, exactly once.
	local line
	line="$(awk -v f="${archive}" '$2 == f' "${CORE_TMP}/checksums.txt")"
	if [[ -z "${line}" || "${line}" == *$'\n'* ]] ||
		! (cd "${CORE_TMP}" && printf '%s\n' "${line}" | sha256sum --check --status); then
		echo "ERROR: checksum verification failed for ${archive}; nothing installed." >&2
		return 1
	fi
	if ! tar -xzf "${CORE_TMP}/${archive}" -C "${CORE_TMP}" riotbox-core; then
		echo "ERROR: release archive ${archive} has no riotbox-core; nothing installed." >&2
		return 1
	fi
	if [[ ! -f "${CORE_BIN}" || -L "${CORE_BIN}" ]]; then
		echo "ERROR: riotbox-core in ${archive} is not a regular file; nothing installed." >&2
		return 1
	fi
}

if [[ "${CORE_SOURCE}" == build ]]; then
	"${SRC_DIR}/scripts/build-core.sh" "${CORE_BIN}"
else
	fetch_release_core
fi

mkdir -p "${DATA_DIR}" "${BIN_DIR}" "${CONFIG_DIR}"

# Surgical removal of just the app tree entries — sessions and backups
# (also under DATA_DIR) survive. Replacing a file with a directory across
# upgrades works because we remove the old entry first.
for p in "${APP_PATHS[@]}"; do
	rm -rf "${DATA_DIR:?}/${p}"
done

for p in "${APP_PATHS[@]}"; do
	[[ -e "${SRC_DIR}/${p}" ]] || continue
	cp -a "${SRC_DIR}/${p}" "${DATA_DIR}/"
done
install -m 0755 "${CORE_BIN}" "${DATA_DIR}/libexec/riotbox-core"
echo "  riotbox-core: ${DATA_DIR}/libexec/riotbox-core (${CORE_SOURCE})"
chmod +x "${DATA_DIR}/bin/riotbox"

# Marker file makes the next upgrade unambiguous about which tree it owns.
: >"${DATA_DIR}/${APP_MARKER}"

ln -sfn "${DATA_DIR}/bin/riotbox" "${BIN_DIR}/riotbox"
echo "  Entrypoint: ${BIN_DIR}/riotbox -> ${DATA_DIR}/bin/riotbox"

# ── Config stubs ─────────────────────────────────────────────────────────
# Seed commented stubs into the user's XDG config. Never overwrite existing
# files. Warn if a newer riotbox-config-version ships than is installed.
STUBS_DIR="${SRC_DIR}/scripts/configs"
for stub in config mounts.conf plugins.conf egress.conf; do
	src="${STUBS_DIR}/${stub}"
	dst="${CONFIG_DIR}/${stub}"
	[[ -f "${src}" ]] || continue
	# Where the shipped stub gets written: the config itself on first install,
	# `<name>.new` beside it when a newer version ships, nowhere otherwise.
	target=""
	if [[ ! -f "${dst}" ]]; then
		target="${dst}"
	else
		# A `config` seeded before the 0600 rule below would keep its loose
		# mode forever: this block re-runs on every install but never rewrites
		# an existing file. Removing group/world access from a per-user config
		# that only its owner ever reads is safe, so do it in place and say
		# so. Owner bits are left alone — a deliberately read-only (0400)
		# config stays read-only. Modes with no group/other bits are already
		# private: leave them and stay quiet.
		if [[ "${stub}" == "config" ]]; then
			# An unreadable mode must not silently mean "already private".
			if ! mode="$(stat -c '%a' "${dst}" 2>/dev/null)" || [[ ! "${mode}" =~ ^[0-7]+$ ]]; then
				mode=777 # unknown mode: fail safe by tightening
			fi
			if ((8#${mode} & 8#077)); then
				chmod go-rwx "${dst}"
				echo "  Config: ${dst} (group/world access removed — may hold credentials)"
			fi
		fi
		shipped_ver="$(grep -m1 '^# riotbox-config-version:' "${src}" 2>/dev/null | awk '{print $NF}' || true)"
		installed_ver="$(grep -m1 '^# riotbox-config-version:' "${dst}" 2>/dev/null | awk '{print $NF}' || true)"
		if [[ -n "${shipped_ver}" ]] && [[ -n "${installed_ver}" ]] &&
			[[ "${shipped_ver}" -gt "${installed_ver}" ]] 2>/dev/null; then
			target="${dst}.new"
		else
			echo "  Config: ${dst} (exists, up to date)"
		fi
	fi
	[[ -n "${target}" ]] || continue

	# `config` is sourced as shell by the launcher and is the documented
	# home of RIOTBOX_PASSTHROUGH_VARS, where users put API keys and
	# tokens — it must never be world-readable, whatever the umask of the
	# shell running this installer. `install -m` sets the mode as the file
	# is created, so it is never briefly readable the way cp-then-chmod
	# would leave it; config.new gets the same treatment because users
	# merge it into (or rename it over) config. mounts.conf, plugins.conf and egress.conf
	# carry no credentials, so their mode is left to the user's umask:
	# tightening them too would be scope creep, not defence. Both paths
	# replace whatever sits at the target (a leftover .new from an earlier
	# upgrade, or a symlink) rather than writing through it.
	if [[ "${stub}" == "config" ]]; then
		install -m 600 "${src}" "${target}"
	else
		cp --remove-destination "${src}" "${target}"
	fi

	if [[ "${target}" == "${dst}" ]]; then
		echo "  Config: ${dst} (created)"
	else
		echo "  Config: ${dst} (exists, v${installed_ver} — v${shipped_ver} available)"
		echo "          Your config is preserved; the new version is at:"
		echo "            ${target}"
		echo "          Review the changes and merge them into your config:"
		echo "            diff ${dst} ${target}"
	fi
done

if ! echo "${PATH}" | tr ':' '\n' | grep -qx "${BIN_DIR}"; then
	echo "Note: ${BIN_DIR} is not in your PATH. Add it:"
	echo "  export PATH=\"${BIN_DIR}:\${PATH}\""
fi
